import fs from 'node:fs';
import { loadProcessor, stats, writeWav } from './harness.mjs';
const out = process.argv[2];
const make = await loadProcessor(48000);
const p = make();
p.send({ type: 'cables', cables: [['u.div2', 'k.trig'], ['c.step', 'w.noteL']] });
p.send({ type: 'params', values: { 'amt.k.trig': 1, 'c.lock': 1, 'c.bpm': 128, 'k.drum': 0.04, 'k.decay': 0.7, 'amt.w.noteL': 0.4 } });
p.send({ type: 'wingie', state: { mode: [1, 2], seq: [[0, 0, 7, 3], [0, 5, 7, 10]] }, resetSeq: [true, true] });
const t0 = Date.now();
const { L, R } = p.renderSeconds(8);
const dt = (Date.now() - t0) / 1000;
console.log('render 8s took', dt.toFixed(2), 's  (realtime x' + (8 / dt).toFixed(1) + ')');
console.log('L', stats(L), 'R', stats(R));
const meters = p.port.posted.filter((m) => m.type === 'meter');
const last = meters.at(-1);
console.log('meters', meters.length, 'seqIdx', last.seqIdx, 'notes', last.notes, 'div', last.div, 'drum', last.drum, 'hz', last.hz.toFixed(2));
console.log('errors', p.port.posted.filter((m) => m.type === 'error'));
const adv = new Set(meters.map((m) => m.seqIdx.join(',')));
console.log('seq positions seen', [...adv]);
if (out) writeWav(out, L, R, 48000, fs);
