#!/usr/bin/env python3
"""Regenerate src/dsp/kastle-samples.js from the Kastle Drum firmware headers.

Usage: python3 -I tools/extract_kastle_samples.py path/to/kastleDrum/TR_HH_AT.h > src/dsp/kastle-samples.js

The Kastle Drum firmware (Bastl Instruments, CC BY-SA) keeps four 8-bit signed
sample tables in TR_HH_AT.h, in this flash order: TR_HH, KICK2, SNARE2, TR_CLAP.
"""
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()
tables = []
for m in re.finditer(r"const char[^\n]*?\b(\w+)_DATA\s*\[\]\s*=\s*\{(.*?)\};", src, re.S):
    name = m.group(1)
    values = [int(v) for v in re.findall(r"-?\d+", m.group(2))]
    tables.append((name, values))

print("// Generated by tools/extract_kastle_samples.py from the Kastle Drum firmware")
print("// (Bastl Instruments, Vaclav Pelousek 2020, CC BY-SA). Do not edit by hand.")
print("// Signed 8-bit sample tables in the order they sit in the ATtiny85 flash.")
print("export const KASTLE_TABLES = [")
for name, values in tables:
    print(f"  {{ name: '{name}', data: [{','.join(str(v) for v in values)}] }},")
print("];")
