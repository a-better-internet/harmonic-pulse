#!/usr/bin/env python3
"""Regenerate src/dsp/kastle-samples.js from the Kastle Drum firmware headers.

Usage:
  python3 -I tools/extract_kastle_samples.py path/to/kastleDrum > src/dsp/kastle-samples.js

Reads the stock tables from kastleDrum/TR_HH_AT.h, plus every *_AT.h sample
and the CHEB3-6 wavetables in kastleDrum/bastlAttinySamples/
(Bastl Instruments, CC BY-SA).
"""
import glob
import os
import re
import sys

root = sys.argv[1]
ARRAY = re.compile(r"const (?:char|int8_t)[^\n]*?\b(\w+?)_DATA\s*\[\]\s*=\s*\{(.*?)\};", re.S)


def tables(path):
    src = open(path, encoding="utf-8").read()
    return [(m.group(1), [int(v) for v in re.findall(r"-?\d+", m.group(2))]) for m in ARRAY.finditer(src)]


samples = {}
for name, data in tables(os.path.join(root, "TR_HH_AT.h")):
    samples[name] = data
lib = os.path.join(root, "bastlAttinySamples")
for path in sorted(glob.glob(os.path.join(lib, "*_AT.h"))):
    for name, data in tables(path):
        samples.setdefault(name, data)
waves = {}
for n in (3, 4, 5, 6):
    for name, data in tables(os.path.join(lib, f"CHEB{n}.h")):
        waves[f"CHEB{n}"] = data

print("// Generated by tools/extract_kastle_samples.py from the Kastle Drum firmware")
print("// (Bastl Instruments, Vaclav Pelousek 2020, CC BY-SA). Do not edit by hand.")
print("// Signed 8-bit sample tables (16384 Hz) and 256-cell Chebyshev wavetables.")
print("export const KASTLE_SAMPLES = {")
for name, data in samples.items():
    print(f"  {name}: [{','.join(map(str, data))}],")
print("};")
print("export const KASTLE_WAVES = {")
for name, data in waves.items():
    print(f"  {name}: [{','.join(map(str, data))}],")
print("};")
